const escapePattern = (value: string) => value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
const patterns = Object.entries(english).filter(([source]) => /\{\d+\}/.test(source))
  .sort(([left], [right]) => right.replace(/\{\d+\}/g, "").length - left.replace(/\{\d+\}/g, "").length)
  .map(([source, target]) => {
  const slots: string[] = [];
  let previous = 0;
  let pattern = "^";
  for (const match of source.matchAll(/\{\d+\}/g)) {
    pattern += escapePattern(source.slice(previous, match.index)) + "([\\s\\S]*?)";
    slots.push(match[0]);
    previous = match.index + match[0].length;
  }
  return { regex: new RegExp(pattern + escapePattern(source.slice(previous)) + "$"), slots, target };
});
const cache = new Map<string, string>();

export function translate(source: string, language: Language): string {
  if (language === "fr" || !source) return source;
  if (Object.hasOwn(english, source)) return english[source];
  const cached = cache.get(source);
  if (cached !== undefined) return cached;
  let result = source;
  for (const { regex, slots, target } of patterns) {
    const match = regex.exec(source);
    if (!match) continue;
    result = target.replace(/\{\d+\}/g, (slot) => match[slots.indexOf(slot) + 1] ?? slot);
    break;
  }
  if (cache.size >= 1024) cache.delete(cache.keys().next().value!);
  cache.set(source, result);
  return result;
}
